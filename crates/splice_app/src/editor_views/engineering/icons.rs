use pxui::{Fill, Label, Node, Paint, Rect, Role, Size, Stroke, Ui};

use super::{INK, LINE, MUTED, QUIET, SECTION_CAPTION, doc_label};

const GAP: f32 = 6.0;
const MIN_TILE: f32 = 84.0;
const TILE_HEIGHT: f32 = 60.0;

pub(super) fn gallery(ui: &mut Ui, width: f32) {
    let columns = ((width + GAP) / (MIN_TILE + GAP)).floor().max(1.0) as usize;
    let tile_width = (width - (columns - 1) as f32 * GAP) / columns as f32;
    for &(name, glyphs) in GROUPS {
        ui.column(
            Node::column()
                .w(Size::Grow)
                .padding(Edges::new(0.0, 14.0, 0.0, 0.0))
                .gap(GAP),
            |ui| {
                doc_label(
                    ui,
                    name,
                    SECTION_CAPTION.size(11.0).role(Role::Heading),
                    MUTED,
                );
                for row in glyphs.chunks(columns) {
                    let row_node =
                        ui.row(Node::row().w(Size::Grow).h_px(TILE_HEIGHT).gap(GAP), |ui| {
                            for glyph in row {
                                let tile = ui.node(
                                    glyph.id,
                                    Node::column()
                                        .w_px(tile_width)
                                        .h_px(TILE_HEIGHT)
                                        .padding(Edges::new(4.0, 11.0, 4.0, 7.0))
                                        .gap(GAP)
                                        .align(Align::Center)
                                        .look(Look::NONE.border(LINE, 1.0)),
                                );
                                ui.within(&tile, &mut |ui| {
                                    let icon = ui.node(
                                        "glyph",
                                        Node::DEFAULT.w_px(22.0).h_px(22.0).role(Role::Image),
                                    );
                                    ui.a11y_name(&icon, glyph.name);
                                    doc_label(
                                        ui,
                                        glyph.id,
                                        Label::MONO.size(10.0).line_height(14.0).w(Size::Fit),
                                        QUIET,
                                    );
                                });
                                ui.tooltip(&tile, glyph.name);
                            }
                        });
                    ui.canvas(&row_node, move |paint, bounds| {
                        for (index, glyph) in row.iter().enumerate() {
                            let x = bounds.x
                                + index as f32 * (tile_width + GAP)
                                + (tile_width - 22.0) * 0.5;
                            draw(
                                paint,
                                Rect::new(x, bounds.y + 11.0, 22.0, 22.0),
                                glyph.shapes,
                            );
                        }
                    });
                }
            },
        );
    }
}

type Point = (f32, f32);

#[derive(Clone, Copy)]
enum Shape {
    Line(Point, Point),
    Curve([Point; 4]),
    Circle(Point, f32),
    Dot(Point),
    Logo,
}

use Shape::{Circle, Curve, Dot, Line, Logo};

struct Glyph {
    id: &'static str,
    name: &'static str,
    shapes: &'static [Shape],
}

fn draw(paint: &mut Paint<'_>, rect: Rect, shapes: &[Shape]) {
    let scale = rect.w / 24.0;
    let map = |(x, y)| (rect.x + x * scale, rect.y + y * scale);
    let stroke = Stroke::new(INK).width(1.6 * scale);
    for &shape in shapes {
        match shape {
            Line(a, b) => {
                let middle = ((a.0 + b.0) * 0.5, (a.1 + b.1) * 0.5);
                paint.curve(map(a), map(middle), map(b), stroke);
            }
            Curve(points) => paint.cubic(points.map(map), stroke),
            Circle(center, radius) => paint.circle(map(center), radius * scale, None, Some(stroke)),
            Dot(center) => paint.circle(map(center), 0.8 * scale, Some(Fill::new(INK)), None),
            Logo => draw_logo(paint, rect, scale),
        }
    }
}

fn draw_logo(paint: &mut Paint<'_>, rect: Rect, scale: f32) {
    let map = |(x, y)| (rect.x + x * scale, rect.y + y * scale);
    let fill = Fill::new(INK).fractional();
    let (x, y) = map((2.0, 2.0));
    paint.fill(
        Rect::new(x + 5.5 * scale, y, 9.0 * scale, 20.0 * scale),
        fill,
    );
    paint.fill(
        Rect::new(x, y + 5.5 * scale, 20.0 * scale, 9.0 * scale),
        fill,
    );
    for x in [7.5, 16.5] {
        for y in [7.5, 16.5] {
            paint.circle(map((x, y)), 5.5 * scale, Some(fill), None);
        }
    }
    let cut = [
        (6.0, 12.5),
        (8.6, 12.5),
        (10.3, 7.5),
        (13.7, 17.5),
        (15.4, 12.5),
        (18.0, 12.5),
    ];
    let stroke = Stroke::new(super::BG).width(2.1 * scale);
    for segment in cut.windows(2) {
        let (a, b) = (segment[0], segment[1]);
        paint.curve(
            map(a),
            map(((a.0 + b.0) * 0.5, (a.1 + b.1) * 0.5)),
            map(b),
            stroke,
        );
    }
}

